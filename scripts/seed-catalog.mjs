#!/usr/bin/env node
/* Generate an idempotent SQL seed of the demo catalog (products, variants, collections, links, coupons).
   Boots the real storefront state in jsdom (same objects the dashboard "import catalog" button uses) and maps
   them with the production mappers in assets/js/domain/catalog-mappers.js — no duplicated transformation logic.
   Usage:  node scripts/seed-catalog.mjs [rootDir] [--out file.sql]      (default: stdout)
   Used by scripts/new-client.mjs to append a `seed` section to supabase/ALL_IN_ONE.sql so a fresh store
   can take orders immediately (restore_create_order_v2 validates products against the tables). */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const outIdx = args.indexOf("--out");
const OUT = outIdx >= 0 ? args[outIdx + 1] : null;
const ROOT =
  args.find((a, i) => !a.startsWith("--") && i !== outIdx + 1) || fileURLToPath(new URL("../", import.meta.url));

/** Boot the real storefront state (window.RESTORE) inside jsdom, LOCAL demo mode, no network. Shared with tests/helpers. */
export async function bootStorefront(root, { page = "index.html" } = {}) {
  const { JSDOM, VirtualConsole } = await import("jsdom");
  const vc = new VirtualConsole();
  const dom = new JSDOM("<!doctype html><html><body></body></html>", {
    url: "http://localhost:8100/" + page,
    virtualConsole: vc,
    pretendToBeVisual: true
  });
  const w = dom.window;
  for (const k of [
    "window",
    "document",
    "navigator",
    "location",
    "localStorage",
    "sessionStorage",
    "HTMLElement",
    "Element",
    "Node",
    "CustomEvent",
    "Event",
    "DOMParser",
    "Blob",
    "Image"
  ]) {
    try {
      Object.defineProperty(globalThis, k, { value: w[k], configurable: true, writable: true });
    } catch {
      /* read-only global */
    }
  }
  globalThis.self = w;
  w.matchMedia = globalThis.matchMedia = () => ({
    matches: false,
    addEventListener() {},
    removeEventListener() {},
    addListener() {},
    removeListener() {}
  });
  w.fetch = globalThis.fetch = async () => {
    throw new Error("no network in seed");
  };
  const run = (file) => w.eval(fs.readFileSync(path.join(root, file), "utf8"));
  run("assets/js/brand.config.js");
  run("assets/js/data.js");
  run("assets/js/config.js");
  w.RESTORE_CONFIG.mode = "local";
  w.RESTORE_CONFIG.demoEnabled = true;
  globalThis.BRAND = w.BRAND;
  globalThis.STORE = w.STORE;
  globalThis.RESTORE_CONFIG = w.RESTORE_CONFIG;
  run("assets/vendor/purify.min.js");
  globalThis.DOMPurify = w.DOMPurify;
  if (!w.requestAnimationFrame) {
    w.requestAnimationFrame = (f) => setTimeout(f, 0);
    globalThis.requestAnimationFrame = w.requestAnimationFrame;
  }
  w.IntersectionObserver = globalThis.IntersectionObserver = class {
    observe() {}
    unobserve() {}
    disconnect() {}
  };
  w.scrollTo = () => {};
  w.alert = () => {};
  w.confirm = () => true;
  await import(pathToFileURL(path.join(root, "assets/js/state.js")).href + "?boot=" + Date.now() + Math.random());
  globalThis.RESTORE = w.RESTORE;
  return { window: w, R: w.RESTORE };
}
export async function loadStorefrontState(root) {
  return (await bootStorefront(root)).R.state;
}

const lit = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const js = (v) => `${lit(JSON.stringify(v ?? {}))}::jsonb`;
const int = (v) => (Number.isFinite(Number(v)) ? Math.trunc(Number(v)) : 0);
const bool = (v) => (v ? "true" : "false");

export function buildSeedSql(state, mappers) {
  const { productToRow, collectionToRow, couponToRow } = mappers;
  const collections = (state.collections || []).map(collectionToRow);
  const colIdByHandle = new Map(collections.map((c) => [c.handle, c.id]));
  const products = (state.products || []).map(productToRow);
  const coupons = (state.settings?.coupons || []).map(couponToRow).filter((c) => c.code);
  const L = [];
  L.push("-- ===== seed: demo catalog (generated by scripts/seed-catalog.mjs — idempotent, safe to re-run) =====");
  L.push("-- Lets a brand-new store take validated orders immediately. Replace the demo products from the dashboard.");
  L.push("begin;");
  for (const c of collections) {
    L.push(
      `insert into public.restore_collections (id, handle, title, description, active, sort_order, extra) values (${lit(c.id)}, ${lit(c.handle)}, ${js(c.title)}, ${js(c.description)}, ${bool(c.active)}, ${int(c.sort_order)}, ${js(c.extra)}) on conflict (id) do nothing;`
    );
  }
  for (const { row, variants, collectionHandles } of products) {
    L.push(
      `insert into public.restore_products (id, handle, title, brand, price, compare_at, stock, condition, specs, images, active, sku, sort_order, extra) values (${lit(row.id)}, ${lit(row.handle)}, ${js(row.title)}, ${lit(row.brand)}, ${int(row.price)}, ${row.compare_at == null ? "null" : int(row.compare_at)}, ${int(row.stock)}, ${lit(row.condition)}, ${js(row.specs)}, ${js(row.images)}, ${bool(row.active)}, ${lit(row.sku)}, ${int(row.sort_order)}, ${js(row.extra)}) on conflict (id) do nothing;`
    );
    for (const v of variants) {
      L.push(
        `insert into public.restore_product_variants (id, product_id, sku, color, storage, price_delta, stock) values (${lit(v.id)}, ${lit(v.product_id)}, ${lit(v.sku)}, ${lit(v.color)}, ${lit(v.storage)}, ${int(v.price_delta)}, ${Math.max(0, int(v.stock))}) on conflict (id) do nothing;`
      );
    }
    (collectionHandles || []).forEach((h, i) => {
      const cid = colIdByHandle.get(String(h));
      if (cid)
        L.push(
          `insert into public.restore_collection_products (collection_id, product_id, sort_order) values (${lit(cid)}, ${lit(row.id)}, ${i}) on conflict do nothing;`
        );
    });
  }
  for (const c of coupons) {
    L.push(
      `insert into public.restore_coupons (code, type, value, min_total, expires_at, usage_limit, active, extra) values (${lit(c.code)}, ${lit(c.type)}, ${int(c.value)}, ${int(c.min_total)}, ${c.expires_at ? lit(c.expires_at) + "::timestamptz" : "null"}, ${c.usage_limit == null ? "null" : int(c.usage_limit)}, ${bool(c.active)}, ${js(c.extra)}) on conflict (code) do nothing;`
    );
  }
  L.push("update public.restore_catalog_meta set version = version + 1, updated_at = now() where id = 'main';");
  L.push("commit;");
  L.push(
    `-- seed summary: ${products.length} products, ${products.reduce((n, p) => n + p.variants.length, 0)} variants, ${collections.length} collections, ${coupons.length} coupons`
  );
  return L.join("\n") + "\n";
}

async function main() {
  const state = await loadStorefrontState(ROOT);
  const mappers = await import(pathToFileURL(path.join(ROOT, "assets/js/domain/catalog-mappers.js")).href);
  const sql = buildSeedSql(state, mappers);
  if (OUT) {
    fs.writeFileSync(OUT, sql);
    console.log(`seed written: ${OUT} (${sql.split("\n").length} lines)`);
  } else process.stdout.write(sql);
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main().catch((e) => {
    console.error("seed failed:", e.message.split("\n")[0]);
    process.exit(1);
  });
}
