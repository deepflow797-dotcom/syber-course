#!/usr/bin/env node
/* Update a client store to a newer template — unattended.
   Two ways to obtain the template:
     --from <dir>          a local checkout of the template (used by the template's release workflow: push mode)
     (default)             GitHub latest release of `package.json → template.repo` (used by the client's own
                           workflow: pull mode). Private repo → set TEMPLATE_TOKEN (fine-grained PAT, contents:read).
   What it does, in order:
     1. Compare versions; stop when the client already has this template version (exit 0, no changes).
     2. Copy every template-owned file over the client, EXCEPT protected ones (config.js, brand.config.js, CLIENT.md,
        LICENSE-CLIENT.txt, ALL_IN_ONE.sql, .env*, backups/) — see scripts/lib/client-sync.mjs.
     3. Delete files the previous template version owned (template-manifest.json) that the new one no longer ships.
     4. Re-derive package.json, re-render branding (apply-brand), Prettier.
     5. `npm ci` + `npm run check` — if the gate fails nothing is committed (exit 1).
     6. Report: new SQL migrations (must be run in Supabase SQL Editor — the only step a robot cannot do without the
        database password), version, changed files. Written to $GITHUB_OUTPUT when present.
   Usage: node scripts/update-from-template.mjs [--from DIR] [--dry-run] [--skip-check] */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execSync } from "node:child_process";
import {
  copyTemplate,
  listTemplateFiles,
  deriveClientPackage,
  isProtected,
  compareVersions,
  CLIENT_CI_YML
} from "./lib/client-sync.mjs";

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : "";
};
const DRY = args.includes("--dry-run");
const SKIP_CHECK = args.includes("--skip-check");
const CLIENT = process.cwd();
const pkgPath = path.join(CLIENT, "package.json");
const clientPkg = JSON.parse(fs.readFileSync(pkgPath, "utf8"));
if (!clientPkg.client?.key) {
  console.error(
    "not a client copy (package.json has no `client.key`) — run this inside a store generated by new-client"
  );
  process.exit(2);
}
const out = (k, v) => {
  console.log(`${k}=${v}`);
  if (process.env.GITHUB_OUTPUT) fs.appendFileSync(process.env.GITHUB_OUTPUT, `${k}=${v}\n`);
};
const sh = (cmd, cwd = CLIENT) => execSync(cmd, { cwd, stdio: "inherit" });

async function fetchTemplate() {
  const repo = clientPkg.template?.repo;
  if (!repo) throw new Error("package.json → template.repo is empty and no --from given");
  const headers = { "User-Agent": "restore-store-updater", Accept: "application/vnd.github+json" };
  if (process.env.TEMPLATE_TOKEN) headers.Authorization = `Bearer ${process.env.TEMPLATE_TOKEN}`;
  const api = `https://api.github.com/repos/${repo}`;
  let res = await fetch(`${api}/releases/latest`, { headers });
  let tag;
  let tarball;
  if (res.ok) {
    const rel = await res.json();
    tag = rel.tag_name;
    tarball = rel.tarball_url;
  } else if (res.status === 404) {
    // no release yet → default branch
    tag = "main";
    tarball = `${api}/tarball`;
  } else throw new Error(`GitHub ${res.status} for ${repo}: ${await res.text()}`);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "template-"));
  res = await fetch(tarball, { headers, redirect: "follow" });
  if (!res.ok) throw new Error(`download failed ${res.status}`);
  fs.writeFileSync(path.join(tmp, "t.tgz"), Buffer.from(await res.arrayBuffer()));
  execSync(`tar -xzf t.tgz`, { cwd: tmp });
  const dir = fs.readdirSync(tmp).find((n) => n !== "t.tgz");
  return { dir: path.join(tmp, dir), ref: tag };
}

function planUpdate(src, templatePkg) {
  const manifestPath = path.join(CLIENT, "template-manifest.json");
  const oldManifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")).files || [] : [];
  const newFiles = listTemplateFiles(src);
  const removed = oldManifest.filter(
    (f) => !newFiles.includes(f) && !isProtected(f) && fs.existsSync(path.join(CLIENT, f))
  );
  const oldMigrations = new Set(oldManifest.filter((f) => f.startsWith("supabase/migrations/")));
  const newMigrations = newFiles.filter((f) => f.startsWith("supabase/migrations/") && !oldMigrations.has(f));
  return { newFiles, removed, newMigrations, templateVersion: templatePkg.version };
}

function applyUpdate(src, templatePkg, plan) {
  copyTemplate(src, CLIENT, { protect: true });
  for (const f of plan.removed) fs.rmSync(path.join(CLIENT, f), { force: true });
  fs.writeFileSync(path.join(CLIENT, ".github/workflows/ci.yml"), CLIENT_CI_YML);
  const auto = path.join(src, "automation/client");
  if (fs.existsSync(auto))
    for (const f of fs.readdirSync(auto))
      fs.copyFileSync(path.join(auto, f), path.join(CLIENT, ".github/workflows", f));
  fs.writeFileSync(
    path.join(CLIENT, "template-manifest.json"),
    JSON.stringify(
      { templateVersion: templatePkg.version, generatedAt: new Date().toISOString(), files: plan.newFiles },
      null,
      2
    ) + "\n"
  );
  const pkg = deriveClientPackage(templatePkg, {
    key: clientPkg.client.key,
    fr: (clientPkg.description || "").replace(/ — online store$/, "") || clientPkg.client.key,
    createdAt: clientPkg.client.createdAt,
    templateRepo: clientPkg.template?.repo
  });
  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n");
  sh("npm ci --no-audit --no-fund");
  sh(`node "${path.join(src, "scripts/apply-brand.mjs")}" "${CLIENT}"`, src);
  sh(
    `node "${path.join(src, "node_modules/prettier/bin/prettier.cjs")}" --log-level warn --write assets/js/brand.config.js package.json`
  );
}

function report(plan, current) {
  out("updated", "true");
  out("version", plan.templateVersion);
  out("previous", current);
  out("migrations", plan.newMigrations.join(" "));
  out("removed", plan.removed.join(" "));
  console.log(`\n✔ ${clientPkg.name} updated to template ${plan.templateVersion}`);
  if (plan.newMigrations.length)
    console.log(`⚠ new database migrations — run in Supabase → SQL Editor:\n  ${plan.newMigrations.join("\n  ")}`);
}

const main = async () => {
  const from = flag("--from");
  const { dir: src, ref } = from ? { dir: path.resolve(from), ref: "local" } : await fetchTemplate();
  const templatePkg = JSON.parse(fs.readFileSync(path.join(src, "package.json"), "utf8"));
  const current = clientPkg.templateVersion || "0.0.0";
  console.log(`client ${clientPkg.name}: template ${current} → candidate ${templatePkg.version} (${ref})`);
  if (compareVersions(templatePkg.version, current) <= 0) {
    out("updated", "false");
    out("version", current);
    console.log("already up to date");
    return;
  }
  if (!fs.existsSync(path.join(src, "node_modules"))) sh("npm ci --no-audit --no-fund", src); // apply-brand deps
  const plan = planUpdate(src, templatePkg);
  if (DRY) {
    console.log(
      `would copy ${plan.newFiles.length} files, delete ${plan.removed.length}: ${plan.removed.join(", ") || "—"}`
    );
    console.log(`new migrations: ${plan.newMigrations.join(", ") || "—"}`);
    return;
  }
  applyUpdate(src, templatePkg, plan);
  if (!SKIP_CHECK) sh("npm run check");
  report(plan, current);
};

main().catch((error) => {
  console.error(error.message || error);
  process.exit(1);
});
